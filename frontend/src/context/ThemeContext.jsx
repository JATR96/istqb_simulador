import {
  createContext,
  useEffect,
  useState
} from "react";

/*
|--------------------------------------------------------------------------
| CONTEXT
|--------------------------------------------------------------------------
*/

export const ThemeContext =
  createContext();

/*
|--------------------------------------------------------------------------
| PROVIDER
|--------------------------------------------------------------------------
*/

export function ThemeProvider({
  children
}) {

  /*
  |--------------------------------------------------------------------------
  | STORAGE
  |--------------------------------------------------------------------------
  */

  const savedTheme =
    localStorage.getItem(
      "theme"
    );

  /*
  |--------------------------------------------------------------------------
  | STATE
  |--------------------------------------------------------------------------
  */

  const [theme, setTheme] =
    useState(
      savedTheme || "light"
    );

  /*
  |--------------------------------------------------------------------------
  | EFFECT
  |--------------------------------------------------------------------------
  */

  useEffect(() => {

    document.body.className =
      theme;

    localStorage.setItem(
      "theme",
      theme
    );

  }, [theme]);

  /*
  |--------------------------------------------------------------------------
  | TOGGLE
  |--------------------------------------------------------------------------
  */

  const toggleTheme = () => {

    setTheme((prev) =>

      prev === "light"
        ? "dark"
        : "light"
    );
  };

  return (
    <ThemeContext.Provider
      value={{
        theme,
        toggleTheme
      }}
    >

      {children}

    </ThemeContext.Provider>
  );
}